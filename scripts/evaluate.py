"""Run the test questions through the full pipeline and score the answers.

For each question in evaluation/test_questions.json the script checks:
- scope:    was the question routed correctly (wine / dish / other)?
- dish:     does the answer suggest at least one dish that suits the wine?
- coverage: for wines missing from the knowledge base, does the answer say so?

The full answers are written to evaluation/results.md, which doubles as the
sample output of the project.

Usage (uses the LLM configured in .env, and an existing index):
    python scripts/evaluate.py
"""

import json
import sys
import time
from datetime import date
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from app import RAGAssistant, build_index  # noqa: E402
from query_utils import fold  # noqa: E402

QUESTIONS_FILE = ROOT / "evaluation" / "test_questions.json"
RESULTS_FILE = ROOT / "evaluation" / "results.md"
NOT_COVERED_PHRASE = "not in my knowledge base"


def score(case: Dict[str, Any], result: Dict[str, Any]) -> Dict[str, bool]:
    """Return pass/fail per check that applies to this test case."""
    answer = fold(result["answer"])
    routed_to = "wine" if result["sources"] else (
        "dish" if "other way around" in answer else "other"
    )
    checks = {"scope": routed_to == case["expected_topic"]}
    if case.get("good_dishes"):
        checks["dish"] = any(fold(dish) in answer for dish in case["good_dishes"])
    if case.get("expect_not_covered"):
        checks["coverage"] = NOT_COVERED_PHRASE in answer
    return checks


def write_report(rows: List[Dict[str, Any]], model: str) -> None:
    """Write a Markdown report with a summary table and every full answer."""
    passed = sum(all(r["checks"].values()) for r in rows)
    lines = [
        "# Evaluation results",
        "",
        f"Generated by `python scripts/evaluate.py` on {date.today().isoformat()} "
        f"with `{model}`. Passed: **{passed}/{len(rows)}** questions.",
        "",
        "| # | Question | Checks | Time |",
        "|---|---|---|---|",
    ]
    for i, r in enumerate(rows, 1):
        checks = ", ".join(f"{k} {'✅' if v else '❌'}" for k, v in r["checks"].items())
        lines.append(f"| {i} | {r['question']} | {checks} | {r['seconds']:.0f}s |")
    for i, r in enumerate(rows, 1):
        res = r["result"]
        lines += [
            "",
            f"## {i}. {r['question']}",
            "",
            f"- Wine search: `{res['wine_query']}`",
            f"- Recipe search: `{res['recipe_query']}`",
            f"- Coverage: {res['coverage_note'].split('.')[0]}",
            "",
            res["answer"].strip(),
        ]
        if res["sources"]:
            lines += ["", "Sources:"]
            lines += [
                f"{n}. {s['title']} (distance {s['distance']:.2f})"
                for n, s in enumerate(res["sources"], 1)
            ]
    RESULTS_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    cases = json.loads(QUESTIONS_FILE.read_text(encoding="utf-8"))
    assistant = RAGAssistant()
    build_index(assistant, rebuild=False)
    model = getattr(assistant.llm, "model", None) or getattr(assistant.llm, "model_name", "unknown")

    rows = []
    for case in cases:
        start = time.time()
        try:
            result = assistant.invoke(case["question"])
        except Exception as e:  # keep evaluating the other questions
            result = {"answer": f"ERROR: {e}", "wine_query": "-", "recipe_query": "-",
                      "coverage_note": "error", "sources": []}
        checks = score(case, result)
        rows.append({"question": case["question"], "result": result, "checks": checks,
                     "seconds": time.time() - start})
        status = "PASS" if all(checks.values()) else "FAIL"
        print(f"{status}  {case['question']}  {checks}")

    write_report(rows, str(model))
    print(f"\nReport written to {RESULTS_FILE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
